"""
zeek/zeek-packages.list -> zeek/zeek-packages.lock (supersedes scripts/zeek_packages_lock_refresh.sh).

Each list entry's ref is resolved the same way the shell script did it:
  - a 40-character commit hash is used as-is
  - a tag (annotated tags peeled) or branch name is resolved with git ls-remote
  - an empty ref tracks the latest GitHub release; if there are no releases, the highest
    version-like tag; if there are none of those, the default branch (zkg's own choice)
"""

import re

from ..base import Checker, entry_flags
from ..core import SHA1_RE, Candidate, Edit, Item, PinError

LOCK_HEADER = (
    '# Generated by scripts/update_pins.py from zeek/zeek-packages.list; do not edit by hand.\n'
    '# Format: URL|commit|resolved ref|environment variables|method\n'
)
VERSION_TAG_RE = re.compile(r'^v?(\d+(?:\.\d+)*)$')


def parse_rows(text):
    rows = []
    for line in (text or '').splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        rows.append(line.split('|'))
    return rows


def github_repo(url):
    m = re.match(r'^https://github\.com/([^/]+/[^/]+?)(?:\.git)?/?$', url)
    return m.group(1) if m else None


class ZeekPackages(Checker):
    category = 'zeek-packages'
    title = 'Zeek packages (zeek-packages.lock)'

    @property
    def paths(self):
        cfg = self.catalog.section('zeek_packages')
        return cfg.get('list', 'zeek/zeek-packages.list'), cfg.get('lock', 'zeek/zeek-packages.lock')

    def discover(self):
        list_rel, lock_rel = self.paths
        list_text = self.index.text(list_rel)
        if list_text is None:
            raise PinError(f'{list_rel} not found')
        lock_text = self.index.text(lock_rel) or ''
        locked = {}
        for row in parse_rows(lock_text):
            row += [''] * (5 - len(row))
            locked[row[0]] = row[:5]
        overrides = self.catalog.section('zeek_packages').get('packages') or {}
        items, listed = [], []
        for n, line in enumerate(list_text.splitlines(), 1):
            if not line.strip() or line.lstrip().startswith('#'):
                continue
            parts = (line.split('|') + [''] * 4)[:4]
            url, ref, env_list, method = (p.strip() for p in parts)
            if not url:
                continue
            listed.append(url)
            old = locked.get(url)
            item = Item(
                self.category,
                url.removeprefix('https://github.com/'),
                f'{old[2]}@{old[1][:12]}' if old else '(not in lock)',
            )
            item.locations = [self.index.location(list_rel, self._offset(list_text, n))]
            item.data.update(url=url, ref=ref, env=env_list, method=method, old=old)
            if github_repo(url):
                item.links.append(('repo', url))
            entry_flags(item, overrides.get(url) or overrides.get(item.name))
            items.append(item)
        for url, row in locked.items():
            if url not in listed:
                item = Item(self.category, url.removeprefix('https://github.com/'), f'{row[2]}@{row[1][:12]}')
                item.data.update(url=url, old=row, removed=True)
                item.candidates = [Candidate('(remove)', label='no longer in zeek-packages.list')]
                items.append(item)
        self._list_order = listed
        self._locked = locked
        self._lock_text = lock_text
        return items

    @staticmethod
    def _offset(text, line_no):
        pos = 0
        for _ in range(line_no - 1):
            pos = text.index('\n', pos) + 1
        return pos

    def _resolve(self, url, ref):
        if SHA1_RE.match(ref):
            return ref, ref
        if ref:
            return self.net.ref_commit(url, ref), ref
        repo = github_repo(url)
        resolved = self.net.gh_latest_release_tag(repo) if repo else None
        if not resolved:
            versions = []
            for t in self.net.tags(url):
                m = VERSION_TAG_RE.match(t)
                if m:
                    versions.append((tuple(map(int, m.group(1).split('.'))), t))
            resolved = max(versions)[1] if versions else None
        if resolved:
            return self.net.ref_commit(url, resolved), resolved
        return self.net.ref_commit(url, 'HEAD'), 'HEAD'

    def lookup(self, item):
        d = item.data
        if d.get('removed'):
            return
        commit, resolved = self._resolve(d['url'], d['ref'])
        if not SHA1_RE.match(commit or ''):
            raise PinError(f'could not resolve {d["ref"] or "latest"} for {d["url"]}')
        new_row = [d['url'], commit, resolved, d['env'], d['method']]
        d['new_row'] = new_row
        old = d['old']
        if old and old[1] == commit and old[2:] == new_row[2:]:
            return
        repo = github_repo(d['url'])
        links = []
        if repo and resolved not in ('HEAD',) and not SHA1_RE.match(resolved):
            links.append(('release', f'https://github.com/{repo}/releases/tag/{resolved}'))
        if repo and old and old[1] != commit:
            links.append(('compare', f'https://github.com/{repo}/compare/{old[1]}...{commit}'))
        label = 'new entry' if not old else ('metadata change' if old[1] == commit else '')
        item.candidates = [Candidate(f'{resolved}@{commit[:12]}', label=label, links=links, data={'row': new_row})]

    def edits(self, item, cand):
        raise NotImplementedError('zeek packages are written by finalize()')

    def finalize(self, selections):
        """Rewrite the lock in list order, taking accepted rows and keeping the rest as they were."""
        list_rel, lock_rel = self.paths
        accepted = {item.data['url']: (item, cand) for item, cand in selections}
        lines = []
        for url in self._list_order:
            if url in accepted:
                lines.append('|'.join(accepted[url][1].data['row']))
            elif url in self._locked:
                lines.append('|'.join(self._locked[url]))
        for url, row in self._locked.items():
            if url not in self._list_order and url not in accepted:
                lines.append('|'.join(row))
        new_text = LOCK_HEADER + ''.join(l + '\n' for l in lines)
        if new_text == self._lock_text:
            return []
        return [Edit(lock_rel, 0, len(self._lock_text), self._lock_text, new_text)]
