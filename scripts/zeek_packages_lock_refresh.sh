# Resolve each Zeek package in zeek/zeek-packages.list to a commit and write zeek/zeek-packages.lock.
#
#   usage: zeek_packages_lock_refresh.sh [list file] [lock file]
#
# Each entry's ref is resolved as follows:
#   - a 40-character commit hash is used as-is
#   - a tag (annotated tags are peeled to their commit) or branch name is resolved with git ls-remote
#   - an empty ref tracks the latest GitHub release; if the repository has no releases, the highest
#     version-like tag; if it has no such tags, the default branch (the same choice zkg makes)
#
# Run it, then review `git diff zeek/zeek-packages.lock` before committing: every changed line is
#   upstream code that will be built into the Zeek image.

set -euo pipefail

SCRIPT_DIR="$(cd -P "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
LIST_FILE="${1:-$REPO_ROOT/zeek/zeek-packages.list}"
LOCK_FILE="${2:-$REPO_ROOT/zeek/zeek-packages.lock}"

for cmd in git curl awk sort; do
  command -v "$cmd" >/dev/null 2>&1 || { echo "$cmd is required" >&2; exit 1; }
done
[[ -r "$LIST_FILE" ]] || { echo "Cannot read $LIST_FILE" >&2; exit 1; }

# print "<commit> <ref name>" for every tag and branch (peeled tag lines end in ^{})
function remote_refs() {
  git ls-remote --tags --heads "$1"
}

# commit for a tag or branch name, preferring the peeled commit of an annotated tag
function commit_for_ref() {
  local refs="$1" name="$2"
  awk -v t="refs/tags/${name}^{}" -v l="refs/tags/${name}" -v h="refs/heads/${name}" '
    $2 == t { peeled = $1 }
    $2 == l { tag = $1 }
    $2 == h { head = $1 }
    END { if (peeled) print peeled; else if (tag) print tag; else if (head) print head }
  ' <<< "$refs"
}

# tag name of the latest GitHub release, or nothing if there are no releases
function latest_github_release() {
  local repo_url="$1" latest_url redirect_url
  latest_url="${repo_url%/}/releases/latest"
  redirect_url="$(curl -fsSLI -o /dev/null -w '%{url_effective}' "$latest_url" 2>/dev/null || true)"
  if [[ -n "$redirect_url" ]] && [[ "$redirect_url" == */releases/tag/* ]]; then
    echo "${redirect_url##*/releases/tag/}"
  fi
}

# highest version-like tag (vX.Y.Z or X.Y.Z), or nothing
function highest_version_tag() {
  awk '{ sub(/^refs\/tags\//, "", $2) } $2 ~ /^v?[0-9]+(\.[0-9]+)*$/ { print $2 }' <<< "$1" \
    | sed 's/^v//' | sort -V | tail -n 1 \
    | while read -r version; do
        # map back to the tag's real name (with or without the v prefix)
        awk -v a="refs/tags/$version" -v b="refs/tags/v$version" '$2 == a || $2 == b { sub(/^refs\/tags\//, "", $2); print $2; exit }' <<< "$1"
      done
}

TMP_LOCK="$(mktemp)"
trap 'rm -f "$TMP_LOCK"' EXIT

cat > "$TMP_LOCK" << HEADER
# Generated by scripts/zeek_packages_lock_refresh.sh from zeek/zeek-packages.list; do not edit by hand.
# Format: URL|commit|resolved ref|environment variables|method
HEADER

while IFS= read -r line || [[ -n "$line" ]]; do
  [[ -z "${line//[[:space:]]/}" || "$line" =~ ^[[:space:]]*# ]] && continue
  IFS='|' read -r url ref env_list method <<< "$line"
  [[ -n "$url" ]] || continue

  refs="$(remote_refs "$url")"
  resolved_ref="$ref"
  commit=""
  if [[ "$ref" =~ ^[0-9a-f]{40}$ ]]; then
    commit="$ref"
  elif [[ -n "$ref" ]]; then
    commit="$(commit_for_ref "$refs" "$ref")"
  else
    resolved_ref="$(latest_github_release "$url")"
    [[ -n "$resolved_ref" ]] || resolved_ref="$(highest_version_tag "$refs")"
    if [[ -n "$resolved_ref" ]]; then
      commit="$(commit_for_ref "$refs" "$resolved_ref")"
    else
      resolved_ref="HEAD"
      commit="$(git ls-remote "$url" HEAD | awk '{ print $1; exit }')"
    fi
  fi

  if [[ ! "$commit" =~ ^[0-9a-f]{40}$ ]]; then
    echo "Could not resolve '${ref:-latest}' for $url" >&2
    exit 1
  fi
  echo "$url  ${resolved_ref} -> ${commit}" >&2
  echo "${url}|${commit}|${resolved_ref}|${env_list}|${method}" >> "$TMP_LOCK"
done < "$LIST_FILE"

mv "$TMP_LOCK" "$LOCK_FILE"
trap - EXIT
chmod 644 "$LOCK_FILE"
echo "Wrote $LOCK_FILE" >&2
